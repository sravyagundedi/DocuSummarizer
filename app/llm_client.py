import random
import time
from dataclasses import dataclass

from langchain_core.messages import HumanMessage
from langchain_core.output_parsers import PydanticOutputParser


@dataclass
class LLMResponse:
    text: str
    input_tokens: int
    output_tokens: int


class LLMClient:
    def __init__(self, settings):
        self.settings = settings

        # Number of retries for temporary real API failures.
        self.max_api_retries = 4

        # ---------------------------------------------------------
        # MOCK PROVIDER
        # ---------------------------------------------------------
        if settings.llm_provider == "mock":
            self.llm = None
            return

        # ---------------------------------------------------------
        # GEMINI
        # ---------------------------------------------------------
        if settings.llm_provider == "gemini":
            if not settings.gemini_api_key:
                raise ValueError("GOOGLE_API_KEY is missing.")

            from langchain_google_genai import ChatGoogleGenerativeAI

            self.llm = ChatGoogleGenerativeAI(
                model=settings.gemini_model,
                google_api_key=settings.gemini_api_key,
                temperature=0,
            )

        # ---------------------------------------------------------
        # OPENAI
        # ---------------------------------------------------------
        elif settings.llm_provider == "openai":
            if not settings.openai_api_key:
                raise ValueError("OPENAI_API_KEY is missing.")

            from langchain_openai import ChatOpenAI

            self.llm = ChatOpenAI(
                model=settings.openai_model,
                api_key=settings.openai_api_key,
                temperature=0,
            )

        else:
            raise ValueError(
                "LLM_PROVIDER must be mock, gemini or openai."
            )

    def _is_retryable_error(self, error):
        """
        Temporary errors where retrying may succeed.
        """

        error_text = str(error).upper()

        retryable_codes = [
            "500",
            "502",
            "503",
            "504",
            "UNAVAILABLE",
            "INTERNAL",
            "DEADLINE_EXCEEDED",
        ]

        return any(
            code in error_text
            for code in retryable_codes
        )

    def _wait_before_retry(self, attempt):
        """
        Exponential backoff with small random jitter.
        """

        base_delay = 2 ** attempt
        jitter = random.uniform(0, 1)
        delay = base_delay + jitter

        print(
            f"Temporary LLM error. "
            f"Retrying in {delay:.1f} seconds..."
        )

        time.sleep(delay)

    # =========================================================
    # MOCK RESPONSE
    # =========================================================

    def _mock_generate(self, prompt):
        """
        Generate deterministic local output.

        This does NOT call Gemini or OpenAI.
        It exists so the complete application can be
        tested without consuming API quota.
        """

        prompt_lower = prompt.lower()

        if "summary" in prompt_lower:
            text = (
                "This is a demo summary generated by DocuSummarizer "
                "Mock Mode. The meeting transcript was successfully "
                "ingested, chunked, and processed through the "
                "summarization pipeline."
            )

        elif "merge" in prompt_lower:
            text = (
                "Demo merged summary: the meeting discussion was "
                "processed successfully and the main discussion "
                "points were consolidated."
            )

        else:
            text = (
                "Demo LLM response generated locally by "
                "DocuSummarizer Mock Mode."
            )

        # Approximate token counts for UI/cost tracking.
        input_tokens = max(1, len(prompt.split()))
        output_tokens = max(1, len(text.split()))

        return LLMResponse(
            text=text,
            input_tokens=input_tokens,
            output_tokens=output_tokens,
        )

    # =========================================================
    # GENERATE
    # =========================================================

    def generate(self, prompt):
        """
        Generate a normal text response.

        Mock mode returns a local deterministic response.
        Gemini/OpenAI use the real API.
        """

        # -----------------------------------------------------
        # MOCK
        # -----------------------------------------------------
        if self.settings.llm_provider == "mock":
            return self._mock_generate(prompt)

        # -----------------------------------------------------
        # REAL PROVIDER
        # -----------------------------------------------------

        last_error = None

        for attempt in range(self.max_api_retries + 1):
            try:
                response = self.llm.invoke(
                    [HumanMessage(content=prompt)]
                )

                content = response.content

                if not isinstance(content, str):
                    content = "".join(
                        p.get("text", "")
                        if isinstance(p, dict)
                        else str(p)
                        for p in content
                    )

                usage = getattr(
                    response,
                    "usage_metadata",
                    {}
                ) or {}

                return LLMResponse(
                    text=content,
                    input_tokens=int(
                        usage.get(
                            "input_tokens",
                            usage.get("prompt_tokens", 0)
                        ) or 0
                    ),
                    output_tokens=int(
                        usage.get(
                            "output_tokens",
                            usage.get("completion_tokens", 0)
                        ) or 0
                    ),
                )

            except Exception as exc:
                last_error = exc
                error_text = str(exc).upper()

                # Do NOT retry daily quota exhaustion.
                if (
                    "RESOURCE_EXHAUSTED" in error_text
                    or "GENERATE_REQUESTS_PER_DAY" in error_text
                    or "QUOTA EXCEEDED" in error_text
                ):
                    raise RuntimeError(
                        "Gemini API daily quota has been exhausted. "
                        "Please wait for the quota reset or use a "
                        "project with available API quota."
                    ) from exc

                if not self._is_retryable_error(exc):
                    raise

                if attempt >= self.max_api_retries:
                    raise RuntimeError(
                        "LLM request failed after "
                        f"{self.max_api_retries + 1} attempts: "
                        f"{exc}"
                    ) from exc

                self._wait_before_retry(attempt)

        raise RuntimeError(
            f"LLM request failed: {last_error}"
        )

    # =========================================================
    # STRUCTURED OUTPUT
    # =========================================================

    def generate_structured(self, prompt, model, retries=2):
        """
        Generate structured Pydantic output.

        Mock mode creates a valid empty StructuredExtraction
        object without making an API call.
        """

        # -----------------------------------------------------
        # MOCK STRUCTURED OUTPUT
        # -----------------------------------------------------
        if self.settings.llm_provider == "mock":
            try:
                # StructuredExtraction currently contains
                # collection fields such as decisions,
                # actions, risks and topics.
                mock_data = {
                    field_name: []
                    for field_name in model.model_fields
                }

                parsed = model.model_validate(mock_data)

                response = LLMResponse(
                    text="{}",
                    input_tokens=max(1, len(prompt.split())),
                    output_tokens=2,
                )

                return parsed, response

            except Exception as exc:
                raise RuntimeError(
                    "Mock structured output could not be created. "
                    f"Check app/schemas.py: {exc}"
                ) from exc

        # -----------------------------------------------------
        # REAL STRUCTURED OUTPUT
        # -----------------------------------------------------

        parser = PydanticOutputParser(
            pydantic_object=model
        )

        instructions = parser.get_format_instructions()

        request = (
            prompt
            + "\n\nFORMAT INSTRUCTIONS:\n"
            + instructions
        )

        last_error = None

        for attempt in range(retries + 1):
            response = self.generate(request)

            try:
                parsed = parser.parse(response.text)

                return parsed, response

            except Exception as exc:
                last_error = exc

                request = (
                    prompt
                    + "\n\nReturn ONLY valid JSON "
                    "matching this schema.\n"
                    "Do not use markdown fences.\n"
                    + instructions
                    + "\n\nPrevious invalid response:\n"
                    + response.text
                )

        raise ValueError(
            "Structured output parsing failed after "
            f"{retries + 1} attempts: {last_error}"
        )